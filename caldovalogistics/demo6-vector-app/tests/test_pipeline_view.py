def test_classify_real_durable_node_sql() -> None:
    for query, expected in NODE_QUERIES.items():
        assert classify_node(query, "knowledge_hub", "chunk_embedding") == expected, query


def test_summarize_reports_stage_state_and_timings() -> None:
    nodes = [
        {"id": str(index), "query": query, "status": "completed", "created_at": "2026-10-16T21:00:00+00:00",
         "updated_at": f"2026-10-16T21:00:0{min(index, 9)}.000+00:00"}
        for index, query in enumerate(NODE_QUERIES)
    ]
    status = {
        "checked_at": "2026-10-16T21:00:20+00:00",
        "pipeline": PIPELINE,
        "runs": [{"id": 24, "status": "completed", "rows_processed": 1, "error": None,
                  "started_at": "2026-10-16T21:00:00+00:00", "completed_at": "2026-10-16T21:00:02.500+00:00",
                  "instance_id": "abc12345"}],
        "nodes": nodes,
        "freshness": {"articles": 12, "searchable_articles": 12, "expected_chunks": 12, "embedded_chunks": 12},
        "sink_rows": 14,
    }

    summary = summarize(status)

    assert summary["run_status"] == "completed"
    assert {key: value["state"] for key, value in summary["stages"].items()} == {
        "source": "completed", "chunk": "completed", "embed": "completed", "sink": "completed", "checkpoint": "completed",
    }
    assert summary["stages"]["source"]["finished_ms"] == 0
    assert summary["stages"]["checkpoint"]["finished_ms"] == 7000
    assert summary["searchable"] is True
    assert summary["checkpoints"] == {"completed": len(NODE_QUERIES), "total": len(NODE_QUERIES)}
    assert "reconciler" not in summary


def test_summarize_marks_running_and_failed_stages() -> None:
    nodes = [
        {"query": "CREATE TABLE knowledge_hub._ai_batch_x AS SELECT * FROM knowledge_hub.article", "status": "completed",
         "updated_at": "2026-10-16T21:00:00.400+00:00"},
        {"query": "WITH numbered AS (SELECT azure_openai.create_embeddings('m', texts))", "status": "failed",
         "updated_at": "2026-10-16T21:00:01+00:00"},
        {"query": "SELECT ai._update_checkpoint('p')", "status": "pending", "updated_at": None},
    ]
    summary = summarize({
        "pipeline": PIPELINE,
        "runs": [{"id": 3, "status": "running", "started_at": "2026-10-16T21:00:00+00:00"}],
        "nodes": nodes,
    })

    assert summary["stages"]["source"] == {"state": "completed", "finished_ms": 400}
    assert summary["stages"]["embed"]["state"] == "failed"
    assert summary["stages"]["checkpoint"]["state"] == "pending"
    assert summary["checkpoints"] == {"completed": 1, "total": 3}
    assert summary["searchable"] is False


def test_demo_uses_only_built_in_features() -> None:
    # No custom pg_durable loop: the pipeline (and pg_durable inside it) does the work.
    schema = (DEMO_ROOT / "sql" / "01-knowledge-hub-schema.sql").read_text(encoding="utf-8")
    assert not (DEMO_ROOT / "sql" / "03-durable-reconciler.sql").exists()
    assert "df.start(" not in schema and "df.loop(" not in schema
    assert "DROP FUNCTION IF EXISTS knowledge_hub.ensure_reconciler(interval);" in schema
    # Superseded vectors are removed at save time instead of by a background job.
    refresh = schema.split("FUNCTION knowledge_hub.refresh_chunk_map", 1)[1].split("$$;", 1)[0]
    assert "DELETE FROM knowledge_hub.chunk_embedding" in refresh and "superseded" in refresh

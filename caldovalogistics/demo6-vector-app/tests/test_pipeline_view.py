from pathlib import Path

from knowledge_hub.pipeline_view import classify_node, render_pipeline_sql, summarize

DEMO_ROOT = Path(__file__).resolve().parents[1]

PIPELINE = {
    "name": "knowledge-hub-pipeline",
    "steps": [
        {"step": "chunk", "column": "embedding_text", "method": "recursive", "overlap": 32, "chunk_size": 256},
        {"step": "embed", "model": "caldova-embedding", "column": "chunk_text", "batch_size": 8, "dimensions": 1536},
    ],
    "paused": False,
    "sink_config": {
        "type": "table",
        "table_name": "chunk_embedding",
        "on_conflict": ["chunk_hash"],
        "schema_name": "knowledge_hub",
        "on_conflict_action": "DO UPDATE SET embedding = EXCLUDED.embedding",
    },
    "trigger_type": "on_change",
    "source_config": {
        "type": "table",
        "table_name": "article",
        "schema_name": "knowledge_hub",
        "incremental_column": "updated_at",
    },
}

INDEX = "CREATE INDEX chunk_embedding_diskann_idx ON knowledge_hub.chunk_embedding USING diskann (embedding vector_cosine_ops)"

# SQL captured from a real pg_durable instance generated by ai.run.
NODE_QUERIES = {
    "CREATE TABLE knowledge_hub._ai_batch_x AS SELECT * FROM knowledge_hub.article WHERE updated_at > '2026-10-16'": "source",
    "CREATE TABLE knowledge_hub._ai_batch_x_chunks (doc_id INT, chunk_index INT, chunk_text TEXT)": "chunk",
    "INSERT INTO knowledge_hub._ai_batch_x_chunks (doc_id, chunk_index, chunk_text) SELECT s.doc_id, c.chunk_index, c.chunk_text FROM (SELECT row_number() OVER ()::INT AS doc_id, * FROM knowledge_hub._ai_batch_x) s, LATERAL azure_ai.chunk(s.embedding_text, 'recursive', 256, 32) AS c(chunk_index, chunk_text)": "chunk",
    "ALTER TABLE knowledge_hub._ai_batch_x_chunks ADD COLUMN IF NOT EXISTS embedding public.vector(1536)": "embed",
    "WITH numbered AS ( SELECT ctid, chunk_text FROM knowledge_hub._ai_batch_x_chunks ), embedded AS ( SELECT azure_openai.create_embeddings('caldova-embedding', texts) ) UPDATE knowledge_hub._ai_batch_x_chunks SET embedding = embedded.emb": "embed",
    "INSERT INTO knowledge_hub.chunk_embedding (doc_id, chunk_index, chunk_text, embedding) SELECT doc_id, chunk_index, chunk_text, embedding FROM knowledge_hub._ai_batch_x_chunks ON CONFLICT (chunk_hash) DO UPDATE SET embedding = EXCLUDED.embedding": "sink",
    "SELECT ai._update_checkpoint('knowledge-hub-pipeline', 'knowledge_hub', 'article', 'updated_at', 'knowledge_hub', '_ai_batch_x_chunks')": "checkpoint",
    "SELECT ai._stamp_rows_processed(8, 'knowledge_hub', '_ai_batch_x_chunks')": "checkpoint",
    "DROP TABLE IF EXISTS knowledge_hub._ai_batch_x_chunks": "cleanup",
}


def test_render_pipeline_sql_tags_each_stage() -> None:
    lines = render_pipeline_sql(PIPELINE, INDEX)
    text = "\n".join(line.text for line in lines)
    by_stage: dict[str, list[str]] = {}
    for line in lines:
        if line.stage:
            by_stage.setdefault(line.stage, []).append(line.text.strip())

    assert "SELECT ai.create_pipeline(" in text
    assert "    source => ai.table_source(" in text
    assert "incremental_column => 'updated_at'" in by_stage["source"]
    assert by_stage["chunk"][0] == "ai.chunk("
    assert by_stage["chunk"][1:5] == [
        "input => 'embedding_text',",
        "method => 'recursive',",
        "chunk_size => 256,",
        "overlap => 32",
    ]
    assert "model => 'caldova-embedding'," in by_stage["embed"]
    assert "on_conflict => ARRAY['chunk_hash']," in by_stage["sink"]
    assert by_stage["trigger"] == ["trigger => 'on_change'"]
    assert by_stage["index"][-1] == INDEX + ";"
    assert [line.number for line in lines] == list(range(1, len(lines) + 1))


def test_render_escapes_single_quotes() -> None:
    pipeline = dict(PIPELINE, sink_config=dict(PIPELINE["sink_config"], on_conflict_action="DO UPDATE SET note = 'x'"))
    text = "\n".join(line.text for line in render_pipeline_sql(pipeline, None))

    assert "on_conflict_action => 'DO UPDATE SET note = ''x'''" in text


